"""
Hebrew hub pages, one per curated tag — /t/<slug>/.

Why this file is separate from tags_config.py: that file decides which documents
carry which tag; this one decides what a human reads when they land on the tag's
page. Matching rules and prose have no business in the same dictionary.

Every entry needs all four fields, and prerender.py builds a page ONLY for tags
listed here. scripts/check_tag_pages.py fails the build if a tag carrying three
documents or more has no entry, if an intro falls outside 80–200 words, or if a
slug is malformed or duplicated.

    slug   ASCII, lowercase, hyphenated. It is the URL and it is PERMANENT:
           changing one orphans every inbound link and every indexed copy.
    h1     The visible heading. Descriptive Hebrew, not a bare tag name.
    group  One of GROUPS. Drives the "נוספים" block at the foot of each page.
    intro  80-200 Hebrew words about what the Geniza documents show.

House style, set after four review passes over the whole corpus:

  * Write about the tag and what the documents show. Do not write about the
    site, the tagging method, or the difficulty of matching a Hebrew string.
    A reader wants the Geniza, not our regular expressions.
  * At most one dash per intro, and most need none. The Academy of the Hebrew
    Language lists the dash among the giveaways of machine-written Hebrew: it
    belongs to print journalism and reads as artificial anywhere else. In
    English the signal has weakened; in Hebrew it has not.
  * Vary the length. An earlier draft had all 142 paragraphs between 80 and 107
    words, a uniformity no human produces. Some subjects deserve 90 words and
    some deserve 180.
  * Do not end on a summarising flourish. Half the corpus once closed with a
    sentence explaining why the topic mattered. End on a fact instead.
  * Break up "A, B and C" triads. Pairs and quartets read as written rather
    than generated.
  * Each observation belongs to one tag. Eight rhetorical templates were
    recurring across five to ten intros each, which meant a reader browsing ten
    pages met the same thought four times.
  * Hebrew typography throughout: maqaf, geresh, gershayim.
"""

