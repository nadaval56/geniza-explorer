_SENTINEL = "{}"


def fix_terms(text, doc_id=None):
    """Normalise the Palestine/Land-of-Israel terminology in one description."""
    if not text or "פל" not in text:
        return text
    if doc_id is not None and str(doc_id) in SKIP_DOCS:
        return text

    # הציטוטים נשלפים החוצה לפני ההחלפה ומוחזרים אחריה, כדי ששום כלל
    # לא יגע בהם — גם לא כלל שייכתב כאן בעתיד.
    keep = []

    def stash(m):
        keep.append(m.group(0))
        return _SENTINEL.format(len(keep) - 1)

    for pattern in PROTECTED:
        text = pattern.sub(stash, text)

    text = GLOSS_TERM.sub("", text)
    text = GLOSS_ECHO.sub(r"\1", text)
    for old, new in REPLACEMENTS:
        text = text.replace(old, new)

    for i, original in enumerate(keep):
        text = text.replace(_SENTINEL.format(i), original)
    return text
