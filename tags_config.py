# ── Word boundaries ──────────────────────────────────────────────────────────
# Hebrew has no \b that works: prefixes (ו/ה/ב/ל/כ/מ/ש) and suffixes glue
# straight onto the stem, so a bare substring search cannot tell "נרד" the
# spikenard from "נרדף" the persecuted. It could not, and for a long time it
# did not: the נרד tag was half persecution, "משי" (silk) caught 245 forms of
# "ממשיך", "דיין" (judge) caught 172 of "עדיין", and the "לחש" pattern behind
# the מאגיה tag caught 75 instances of "לחשבונות".
#
# w() builds a bounded pattern: an optional short prefix, the stem, an optional
# suffix from an explicit list, and no other Hebrew letter glued to either end.
#
# The prefix set is narrowed per word wherever the full set would swallow the
# very letter that makes the false positive: ש is dropped for חיטה, because
# otherwise ש+חיטה matches "שחיטה" (slaughter), and מ is dropped for תמר,
# because otherwise מ+ש+תמר+ים matches "משתמרים".
_HEB = "א-ת"          # includes the final forms ך ם ן ף ץ — they sit in this range
_PREFIX = "והבלכמש"

def w(*stems, pre=_PREFIX, suf=""):
    """Bounded match for Hebrew stems.

    pre  — letters allowed to precede the stem, up to two of them ("" for none)
    suf  — alternation of allowed endings, e.g. "ים|ות|י"
    """
    head = f"[{pre}]{{0,2}}" if pre else ""
    tail = f"(?:{suf})?" if suf else ""
    return rf"(?<![{_HEB}]){head}(?:{'|'.join(stems)}){tail}(?![{_HEB}])"


