from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn
from docx.oxml import OxmlElement


def set_rtl(paragraph):
    pPr = paragraph._p.get_or_add_pPr()
    bidi = OxmlElement("w:bidi")
    pPr.append(bidi)
    paragraph.alignment = WD_ALIGN_PARAGRAPH.RIGHT


def set_run_rtl(run):
    rPr = run._r.get_or_add_rPr()
    rtl = OxmlElement("w:rtl")
    rPr.append(rtl)


def add_para(doc, text, *, bold=False, italic=False, size=12, color=None,
             align=WD_ALIGN_PARAGRAPH.JUSTIFY, space_after=8, first_line_indent=None):
    p = doc.add_paragraph()
    set_rtl(p)
    p.alignment = align
    pf = p.paragraph_format
    pf.space_after = Pt(space_after)
    pf.line_spacing = 1.4
    if first_line_indent:
        pf.first_line_indent = Cm(first_line_indent)
    r = p.add_run(text)
    r.font.name = "David"
    rPr = r._r.get_or_add_rPr()
    rFonts = OxmlElement("w:rFonts")
    rFonts.set(qn("w:cs"), "David")
    rFonts.set(qn("w:ascii"), "David")
    rFonts.set(qn("w:hAnsi"), "David")
    rPr.append(rFonts)
    r.font.size = Pt(size)
    r.bold = bold
    r.italic = italic
    if color:
        r.font.color.rgb = color
    set_run_rtl(r)
    return p


def add_h1(doc, text):
    return add_para(doc, text, bold=True, size=22,
                    color=RGBColor(0x8B, 0x6F, 0x2E),
                    align=WD_ALIGN_PARAGRAPH.RIGHT, space_after=6)


def add_subtitle(doc, text):
    return add_para(doc, text, italic=True, size=12,
                    color=RGBColor(0x55, 0x55, 0x55),
                    align=WD_ALIGN_PARAGRAPH.RIGHT, space_after=18)


def add_h2(doc, text):
    return add_para(doc, text, bold=True, size=15,
                    color=RGBColor(0x33, 0x33, 0x33),
                    align=WD_ALIGN_PARAGRAPH.RIGHT, space_after=6)


def add_pullquote(doc, text):
    return add_para(doc, text, italic=True, size=12,
                    color=RGBColor(0x66, 0x55, 0x33),
                    align=WD_ALIGN_PARAGRAPH.RIGHT, space_after=12,
                    first_line_indent=0.6)


def add_caption(doc, text):
    return add_para(doc, text, italic=True, size=10,
                    color=RGBColor(0x77, 0x77, 0x77),
                    align=WD_ALIGN_PARAGRAPH.RIGHT, space_after=14)


